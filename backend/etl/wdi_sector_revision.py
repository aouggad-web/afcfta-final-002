def latest(iso3, table):
    """(année, valeur) la plus récente pour un pays, ou (None, None)."""
    series = table.get(iso3) or {}
    if not series:
        return None, None
    y = max(series)
    return y, series[y]


def series_mva_mln(iso3):
    """Série MVA (mln USD courants) 2023-2025 d'un pays : {année: mln}."""
    return {y: round(v / 1e6, 1) for y, v in sorted((MVA_USD.get(iso3) or {}).items())}


def per_capita(iso3, year):
    usd = (MVA_USD.get(iso3) or {}).get(year)
    pop = (POPULATION.get(iso3) or {}).get(year)
    if usd and pop:
        return round(usd / pop, 1)
    return None
